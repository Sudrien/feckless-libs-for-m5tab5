"""
ipa12.py -- the IPA letters Ark Pixel has no glyphs for at 12px, drawn
for Ark12's 6x12 halfwidth cell (gen_ark12.py's add_ipa()).

Ark's 12px cut stops at Latin Extended-B: IPA Extensions (U+0250-02AF),
the Spacing Modifier Letters IPA uses (stress, length, superscripts) and
the Phonetic Extensions' barred small capitals are not in it at any cut.
Galmuri, which supplies the Hangul, has the IPA letters, but its Latin is
7 px wide on an 8-row x-height against Ark's 5 on 6: they would sit in
the line as a different, larger font. So they are drawn here, in Ark's
metrics -- x-height rows 4-9, ascenders from row 2, descenders to row 11,
the letter in columns 0-4 and column 5 the gap, which only a retroflex
tail or a hook to the right may use.

Three kinds of entry:

  TURNED    an Ark glyph turned 180 degrees about the centre of the
            x-height band (row r -> 13 - r, column c -> 4 - c): IPA's
            turned letters are exactly that, so a -> ɐ keeps Ark's a.
  MIRRORED  an Ark glyph flipped left to right (c -> 4 - c).
  DRAWN     rows of '#' and '.', top row first, starting at the row
            given; rows not given are blank.

  COPIED    an Ark glyph as it is, under the IPA codepoint (ɡ is Ark's
            single-storey g; ǃ its exclamation mark).

A source named by TURNED or MIRRORED may itself be DRAWN here: DRAWN is
built first.

SPDX-License-Identifier: MIT
"""

