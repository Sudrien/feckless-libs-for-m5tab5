def _rows_of(top, art):
    rows = [0] * H
    for i, line in enumerate(art):
        for c, ch in enumerate(line):
            if ch == "#":
                if c >= W:
                    raise ValueError("wider than the cell")
                rows[top + i] |= 1 << c
    return rows


def _turn(rows):
    out = [0] * H
    for r in range(H):
        for c in range(5):
            if rows[r] >> c & 1:
                out[13 - r] |= 1 << (4 - c)
    return out


def _mirror(rows):
    out = [0] * H
    for r in range(H):
        for c in range(5):
            if rows[r] >> c & 1:
                out[r] |= 1 << (4 - c)
    return out


def glyphs(ark):
    """codepoint -> (6, 12 rows) for every IPA glyph here, from `ark`
    (codepoint -> (width, rows)), the table gen_ark12.py has built."""
    out = {}

    def src(cp):
        if cp in out:
            return out[cp][1]
        w, rows = ark[cp]
        if w != W:
            raise ValueError(f"U+{cp:04X} is not halfwidth")
        return rows

    for cp, (top, art) in DRAWN.items():
        out[cp] = (W, _rows_of(top, art))
    for cp, s in COPIED.items():
        out[cp] = (W, list(src(s)))
    for cp, s in TURNED.items():
        rows = src(s)
        if rows[0] or rows[1]:
            raise ValueError(f"U+{s:04X} reaches row 0 or 1: turned, it "
                             "would fall out of the cell")
        out[cp] = (W, _turn(rows))
    for cp, s in MIRRORED.items():
        out[cp] = (W, _mirror(src(s)))
    return out
